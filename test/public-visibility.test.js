import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { createStore, createUser, createArtifact, listArtifacts, getArtifact, updateArtifact, setAccessMode, setArtifactSharing, previewAccessMode, canReadArtifactEvent, listEventsSince, getArtifactPermission } from "../src/lib/storage.js";
import { eventVisibleTo } from "../src/lib/events.js";

test("public mode distinguishes anonymous public reads from authenticated team collaboration", async (t) => {
  const home = await mkdtemp(path.join(tmpdir(), "artifacty-public-"));
  t.after(() => rm(home, { recursive: true, force: true }));
  const store = createStore({ home });
  const adminUser = await createUser(store, { email: "admin@example.test", password: "password123", role: "admin" });
  const member = await createUser(store, { email: "member@example.test", password: "password123" });
  const admin = { userId: adminUser.id, role: "admin" };
  const user = { userId: member.id, role: "user" };
  const anonymous = { anonymous: true };
  const artifacts = {};
  for (const visibility of ["public", "team", "private"]) artifacts[visibility] = await createArtifact(store, { title: `${visibility} searchable`, content: "body", visibility, access: admin });
  assert.deepEqual((await listArtifacts(store, { access: anonymous })).map((a) => a.id), [artifacts.public.id]);
  assert.deepEqual((await listArtifacts(store, { access: anonymous, query: "searchable" })).map((a) => a.id), [artifacts.public.id]);
  assert.equal((await getArtifact(store, artifacts.public.id, { access: anonymous })).content, "body");
  for (const visibility of ["team", "private"]) await assert.rejects(getArtifact(store, artifacts[visibility].id, { access: anonymous }), { statusCode: 404 });
  assert.equal((await listArtifacts(store, { access: user })).length, 2);
  assert.equal(await getArtifactPermission(store, artifacts.public.id, { access: anonymous }), "read");
  for (const access of [anonymous, user]) await assert.rejects(updateArtifact(store, artifacts.public.id, { content: "changed", access }), { statusCode: 403 });
  await updateArtifact(store, artifacts.team.id, { content: "collaborative", access: user });
  assert.deepEqual((await previewAccessMode(store, "public", { access: admin })).artifacts.map((a) => a.id), [artifacts.public.id]);
  const events = await listEventsSince(store, 0, {}, 200, anonymous);
  assert.ok(events.length > 0);
  assert.ok(events.every((event) => event.artifactId === artifacts.public.id));
  assert.equal(await canReadArtifactEvent(store, { artifactId: artifacts.team.id }, anonymous), false);
  assert.equal(eventVisibleTo({ visibility: "team", ownerUserId: admin.userId }, anonymous), false);
  assert.equal(eventVisibleTo({ visibility: "public" }, anonymous), true);
  await setAccessMode(store, "private", { access: admin });
  assert.deepEqual(await listArtifacts(store, { access: anonymous }), []);
  await assert.rejects(getArtifact(store, artifacts.public.id, { access: anonymous }), { statusCode: 404 });
  await assert.rejects(getArtifact(store, artifacts.public.id, { access: user }), { statusCode: 404 });
  assert.equal(await canReadArtifactEvent(store, { artifactId: artifacts.public.id }, anonymous), false);
  await setArtifactSharing(store, artifacts.public.id, { userIds: [user.userId], teamIds: [] }, { access: admin });
  assert.equal((await getArtifact(store, artifacts.public.id, { access: user })).id, artifacts.public.id);
  await assert.rejects(updateArtifact(store, artifacts.public.id, { content: "changed", access: user }), { statusCode: 403 });
});
