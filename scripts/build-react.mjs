#!/usr/bin/env node
// Build the committed React 19 browser bundle used by the gated React renderer.
//
// React 19 ships no UMD or browser ESM build, only CommonJS. The four
// production CommonJS files that a browser needs are plain `require` modules
// with no other dependencies, so this script wraps them in a tiny module
// loader instead of adding a bundler. It exposes `window.React` and
// `window.ReactDOM` (react-dom plus react-dom/client) as a classic script.
//
//   node scripts/build-react.mjs           write src/client/react-bundle.js
//   node scripts/build-react.mjs --check   fail when the committed bundle is stale
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
export const REACT_BUNDLE_FILE = path.join(root, "src", "client", "react-bundle.js");
export const REACT_BUNDLE_BANNER = /^\/\*! artifacty react bundle: react@(\S+) react-dom@(\S+) scheduler@(\S+) \|/;

// Module id -> production file. The package index.js files only choose between
// the development and production files, so this table replaces them.
const MODULES = [
  ["react", "react/cjs/react.production.js"],
  ["scheduler", "scheduler/cjs/scheduler.production.js"],
  ["react-dom", "react-dom/cjs/react-dom.production.js"],
  ["react-dom/client", "react-dom/cjs/react-dom-client.production.js"]
];

async function installedVersion(packageName) {
  const file = path.join(root, "node_modules", packageName, "package.json");
  return JSON.parse(await readFile(file, "utf8")).version;
}

export async function buildReactBundle() {
  const react = await installedVersion("react");
  const reactDom = await installedVersion("react-dom");
  const scheduler = await installedVersion("scheduler");
  if (!react.startsWith("19.")) {
    throw new Error(`Expected react 19.x, found ${react}. Run npm install first.`);
  }
  if (reactDom !== react) {
    throw new Error(`react-dom ${reactDom} does not match react ${react}.`);
  }
  const definitions = [];
  for (const [id, file] of MODULES) {
    const source = await readFile(path.join(root, "node_modules", file), "utf8");
    for (const match of source.matchAll(/\brequire\(["']([^"']+)["']\)/g)) {
      if (!MODULES.some(([moduleId]) => moduleId === match[1])) {
        throw new Error(`${file} requires ${match[1]}, which this bundle does not include.`);
      }
    }
    definitions.push(`${JSON.stringify(id)}: function (module, exports, require) {\n${source}\n}`);
  }
  return `/*! artifacty react bundle: react@${react} react-dom@${reactDom} scheduler@${scheduler} | MIT | Copyright (c) Meta Platforms, Inc. and affiliates | Generated by npm run build:react */
(function () {
  "use strict";
  var definitions = {
${definitions.join(",\n")}
  };
  var cache = {};
  function load(id) {
    if (!Object.prototype.hasOwnProperty.call(definitions, id)) {
      throw new Error("Module not bundled: " + id);
    }
    if (!cache[id]) {
      var module = { exports: {} };
      cache[id] = module;
      definitions[id].call(module.exports, module, module.exports, load);
    }
    return cache[id].exports;
  }
  window.React = load("react");
  window.ReactDOM = Object.assign({}, load("react-dom"), load("react-dom/client"));
})();
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const bundle = await buildReactBundle();
  if (process.argv.includes("--check")) {
    const committed = await readFile(REACT_BUNDLE_FILE, "utf8").catch(() => "");
    if (committed !== bundle) {
      console.error("src/client/react-bundle.js is stale. Run npm run build:react and commit the result.");
      process.exit(1);
    }
    console.log("React bundle is current.");
  } else {
    await writeFile(REACT_BUNDLE_FILE, bundle);
    console.log(`Built React bundle (${Buffer.byteLength(bundle)} bytes).`);
  }
}
